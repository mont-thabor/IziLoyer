CREATE TABLE izl_t_user (
  id           bigint GENERATED BY DEFAULT AS IDENTITY,
  nom          varchar(80)  NOT NULL,
  prenoms      varchar(120) NOT NULL,
  telephone    varchar(16)  NOT NULL,              -- E.164 : +225…
  email        citext,
  role         izl_typ_user_role NOT NULL,
  created_at   timestamptz  NOT NULL DEFAULT now(),
  updated_at   timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_user            PRIMARY KEY (id),
  CONSTRAINT izl_uq_user_telephone  UNIQUE (telephone),
  CONSTRAINT izl_uq_user_email      UNIQUE (email),
  CONSTRAINT izl_ck_user_telephone  CHECK (telephone ~ '^\+[0-9]{8,15}$')
);

CREATE TABLE izl_t_site (
  id               bigint GENERATED BY DEFAULT AS IDENTITY,
  proprietaire_id  bigint       NOT NULL,
  nom              varchar(120) NOT NULL,
  commune          varchar(80)  NOT NULL,
  ville            varchar(80)  NOT NULL DEFAULT 'Abidjan',
  created_at       timestamptz  NOT NULL DEFAULT now(),
  updated_at       timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_site              PRIMARY KEY (id),
  CONSTRAINT izl_fk_site_proprietaire FOREIGN KEY (proprietaire_id) REFERENCES izl_t_user (id)
);
CREATE INDEX izl_ix_site_proprietaire ON izl_t_site (proprietaire_id);

CREATE TABLE izl_t_local (
  id             bigint GENERATED BY DEFAULT AS IDENTITY,
  site_id        bigint      NOT NULL,
  designation    varchar(80) NOT NULL,
  type           varchar(40) NOT NULL,               -- Studio, 2 pièces…
  loyer_mensuel  bigint      NOT NULL,               -- valeur par défaut du bail
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_local              PRIMARY KEY (id),
  CONSTRAINT izl_uq_local_designation  UNIQUE (site_id, designation),
  CONSTRAINT izl_fk_local_site         FOREIGN KEY (site_id) REFERENCES izl_t_site (id),
  CONSTRAINT izl_ck_local_loyer        CHECK (loyer_mensuel > 0)
);
CREATE INDEX izl_ix_local_site ON izl_t_local (site_id);

CREATE TABLE izl_t_lease (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY,
  local_id            bigint      NOT NULL,
  locataire_id        bigint      NOT NULL,
  numero_wave         varchar(16) NOT NULL,            -- numéro Wave PAYEUR du locataire
  loyer_mensuel       bigint      NOT NULL,            -- porté par le bail (décision v1.1 #3)
  jour_limite         smallint    NOT NULL DEFAULT 5,
  date_debut_contrat  date,                            -- informative, peut être antérieure
  date_prise_effet    date        NOT NULL,            -- 1er mois géré dans IziLoyer
  date_fin            date,                            -- NULL = reconduction tacite
  statut              izl_typ_lease_status NOT NULL DEFAULT 'ACTIF',
  receipt_seq         integer     NOT NULL DEFAULT 0,  -- compteur de quittances
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_lease               PRIMARY KEY (id),
  CONSTRAINT izl_fk_lease_local         FOREIGN KEY (local_id)     REFERENCES izl_t_local (id),
  CONSTRAINT izl_fk_lease_locataire     FOREIGN KEY (locataire_id) REFERENCES izl_t_user (id),
  CONSTRAINT izl_ck_lease_numero_wave   CHECK (numero_wave ~ '^\+[0-9]{8,15}$'),
  CONSTRAINT izl_ck_lease_jour_limite   CHECK (jour_limite BETWEEN 4 AND 28),   -- D10
  CONSTRAINT izl_ck_lease_loyer         CHECK (loyer_mensuel > 0),
  CONSTRAINT izl_ck_lease_debut         CHECK (date_debut_contrat IS NULL OR date_debut_contrat <= date_prise_effet),
  CONSTRAINT izl_ck_lease_fin           CHECK (date_fin IS NULL OR date_fin >= date_prise_effet)
);
-- ⚠️ SFD-02 : un seul bail ACTIF par local (index unique partiel)
CREATE UNIQUE INDEX izl_ix_lease_local_actif ON izl_t_lease (local_id) WHERE statut = 'ACTIF';
CREATE INDEX izl_ix_lease_locataire ON izl_t_lease (locataire_id);
CREATE INDEX izl_ix_lease_statut    ON izl_t_lease (statut);

CREATE TABLE izl_t_installment (
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  lease_id        bigint      NOT NULL,
  type            izl_typ_installment_type NOT NULL DEFAULT 'LOYER',
  mois            date,                                -- 1er du mois ; NULL si REPRISE
  libelle         varchar(120),                        -- obligatoire si REPRISE
  montant_du      bigint      NOT NULL,
  montant_percu   bigint      NOT NULL DEFAULT 0,      -- jamais affecté : incrément atomique
  statut_paiement izl_typ_payment_status NOT NULL DEFAULT 'EN_ATTENTE', -- tenu par trigger
  est_en_retard   boolean     NOT NULL DEFAULT false,  -- recalculé par le cron 00:05
  date_echeance   date        NOT NULL,                -- REPRISE : date limite fixée par le bailleur
  saisi_par       bigint,                              -- renseigné pour REPRISE
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_installment            PRIMARY KEY (id),
  CONSTRAINT izl_fk_installment_lease      FOREIGN KEY (lease_id)  REFERENCES izl_t_lease (id),
  CONSTRAINT izl_fk_installment_saisi_par  FOREIGN KEY (saisi_par) REFERENCES izl_t_user (id),
  CONSTRAINT izl_ck_installment_type_mois  CHECK ((type = 'LOYER') = (mois IS NOT NULL)),
  CONSTRAINT izl_ck_installment_libelle    CHECK (type <> 'REPRISE' OR libelle IS NOT NULL),
  CONSTRAINT izl_ck_installment_montant_du CHECK (montant_du > 0),
  CONSTRAINT izl_ck_installment_percu      CHECK (montant_percu >= 0 AND montant_percu <= montant_du)
);
-- ⚠️ Unicité (bail, mois) pour les loyers — les REPRISE (mois NULL) y échappent
CREATE UNIQUE INDEX izl_ix_installment_lease_mois ON izl_t_installment (lease_id, mois) WHERE type = 'LOYER';
CREATE INDEX izl_ix_installment_lease  ON izl_t_installment (lease_id);
CREATE INDEX izl_ix_installment_retard ON izl_t_installment (lease_id) WHERE est_en_retard;
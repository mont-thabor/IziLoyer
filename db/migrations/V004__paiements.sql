CREATE TABLE izl_t_owner_wave_account (
  id                      bigint GENERATED BY DEFAULT AS IDENTITY,
  owner_id                bigint      NOT NULL,       -- UNIQUE : un seul compte Wave par bailleur (V1)
  numero_wave             varchar(16) NOT NULL,       -- compte BÉNÉFICIAIRE
  api_key_chiffree        text        NOT NULL,       -- AES-256-GCM côté application
  api_secret_chiffre      text        NOT NULL,       -- (clé dans les variables d'environnement)
  webhook_secret_chiffre  text        NOT NULL,       -- jamais en clair en base
  statut                  izl_typ_wave_account_status NOT NULL DEFAULT 'ACTIF',
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_owa             PRIMARY KEY (id),
  CONSTRAINT izl_uq_owa_owner       UNIQUE (owner_id),
  CONSTRAINT izl_fk_owa_owner       FOREIGN KEY (owner_id) REFERENCES izl_t_user (id),
  CONSTRAINT izl_ck_owa_telephone   CHECK (numero_wave ~ '^\+[0-9]{8,15}$')
);

CREATE TABLE izl_t_checkout_session (
  id               bigint GENERATED BY DEFAULT AS IDENTITY,
  lease_id         bigint      NOT NULL,
  wave_session_id  varchar(64),
  client_reference varchar(64) NOT NULL,               -- rattachement webhook ↔ bail
  montant          bigint      NOT NULL,               -- ≤ dette cumulée (D2/D11, contrôlé applicatif)
  statut           izl_typ_session_status NOT NULL DEFAULT 'OUVERTE',
  expires_at       timestamptz NOT NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_checkout_session PRIMARY KEY (id),
  CONSTRAINT izl_uq_cs_wave_session  UNIQUE (wave_session_id),
  CONSTRAINT izl_uq_cs_reference     UNIQUE (client_reference),
  CONSTRAINT izl_fk_cs_lease         FOREIGN KEY (lease_id) REFERENCES izl_t_lease (id),
  CONSTRAINT izl_ck_cs_montant       CHECK (montant > 0)
);
-- ⚠️ Une seule session OUVERTE par bail
CREATE UNIQUE INDEX izl_ix_cs_lease_ouverte ON izl_t_checkout_session (lease_id) WHERE statut = 'OUVERTE';
CREATE INDEX izl_ix_cs_ouvertes_expires ON izl_t_checkout_session (expires_at) WHERE statut = 'OUVERTE';

CREATE TABLE izl_t_transfer_verification (
  id                     bigint GENERATED BY DEFAULT AS IDENTITY,
  lease_id               bigint      NOT NULL,
  montant_declare        bigint      NOT NULL,        -- indicatif ; le montant Wave fait foi
  reference_declaree     varchar(64),
  wave_transaction_id    varchar(64),                 -- renseigné quand la transaction est trouvée
  statut                 izl_typ_verification_status NOT NULL DEFAULT 'EN_VERIFICATION',
  tentatives             smallint    NOT NULL DEFAULT 0,
  prochaine_tentative_at timestamptz,
  expire_at              timestamptz NOT NULL,        -- +24 h max (retries bornés)
  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_transfer_verification PRIMARY KEY (id),
  CONSTRAINT izl_fk_tv_lease              FOREIGN KEY (lease_id) REFERENCES izl_t_lease (id),
  CONSTRAINT izl_ck_tv_montant            CHECK (montant_declare > 0)
);
-- ⚠️ Une transaction Wave ne peut être revendiquée qu'une fois
CREATE UNIQUE INDEX izl_ix_tv_wave_tx ON izl_t_transfer_verification (wave_transaction_id) WHERE wave_transaction_id IS NOT NULL;
CREATE INDEX izl_ix_tv_a_traiter ON izl_t_transfer_verification (prochaine_tentative_at) WHERE statut = 'EN_VERIFICATION';

CREATE TABLE izl_t_wave_event (
  id             bigint GENERATED BY DEFAULT AS IDENTITY,
  transaction_id varchar(64) NOT NULL,
  event_type     varchar(40) NOT NULL,
  source         izl_typ_event_source NOT NULL,          -- WEBHOOK / RECONCILIATION / VERIF_VOIE_B
  statut_brut    varchar(40),
  montant_brut   bigint,
  date_reception timestamptz NOT NULL DEFAULT now(),
  traite         boolean     NOT NULL DEFAULT false,   -- seul champ modifiable (trigger)
  payload        jsonb       NOT NULL,                 -- payload brut, audit
  CONSTRAINT izl_pk_wave_event        PRIMARY KEY (id),
  CONSTRAINT izl_uq_wave_event_tx_type UNIQUE (transaction_id, event_type)  -- ⚠️ idempotence niveau 1
);
COMMENT ON TABLE izl_t_wave_event IS 'Append-only. Seul le champ traite est modifiable (trigger izl_tg_wave_event_immutable).';

CREATE TABLE izl_t_payment (
  id               bigint GENERATED BY DEFAULT AS IDENTITY,
  lease_id         bigint      NOT NULL,
  wave_event_id    bigint,                            -- NULL ssi voie = OUVERTURE
  voie             izl_typ_payment_channel NOT NULL,  -- A / B / OUVERTURE (avance déclarée)
  montant          bigint      NOT NULL,              -- TOUJOURS le montant renvoyé par Wave
  excedent_initial bigint      NOT NULL DEFAULT 0,    -- surplus créé ou avance (immuable)
  excedent_restant bigint      NOT NULL DEFAULT 0,    -- crédit non encore consommé
  date_paiement    timestamptz NOT NULL DEFAULT now(),
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_payment            PRIMARY KEY (id),
  CONSTRAINT izl_uq_payment_wave_event UNIQUE (wave_event_id),                      -- ⚠️ idempotence niveau 2
  CONSTRAINT izl_fk_payment_lease      FOREIGN KEY (lease_id)      REFERENCES izl_t_lease (id),
  CONSTRAINT izl_fk_payment_wave_event FOREIGN KEY (wave_event_id) REFERENCES izl_t_wave_event (id),
  CONSTRAINT izl_ck_payment_montant    CHECK (montant > 0),
  CONSTRAINT izl_ck_payment_excedent   CHECK (excedent_initial >= 0 AND excedent_restant >= 0
                                              AND excedent_restant <= excedent_initial),
  CONSTRAINT izl_ck_payment_ouverture  CHECK ((voie = 'OUVERTURE') = (wave_event_id IS NULL))
);
-- ⚠️ Une seule avance d'ouverture par bail
CREATE UNIQUE INDEX izl_ix_payment_ouverture ON izl_t_payment (lease_id) WHERE voie = 'OUVERTURE';
CREATE INDEX izl_ix_payment_lease ON izl_t_payment (lease_id);
CREATE INDEX izl_ix_payment_date  ON izl_t_payment (date_paiement);

CREATE TABLE izl_t_payment_allocation (
  id             bigint GENERATED BY DEFAULT AS IDENTITY,
  payment_id     bigint      NOT NULL,
  installment_id bigint      NOT NULL,
  montant        bigint      NOT NULL,
  source         izl_typ_allocation_source NOT NULL DEFAULT 'PAIEMENT',  -- PAIEMENT ou CREDIT
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_payment_allocation        PRIMARY KEY (id),
  CONSTRAINT izl_uq_alloc_payment_installment UNIQUE (payment_id, installment_id), -- ⚠️ idempotence niveau 3
  CONSTRAINT izl_fk_alloc_payment     FOREIGN KEY (payment_id)     REFERENCES izl_t_payment (id),
  CONSTRAINT izl_fk_alloc_installment FOREIGN KEY (installment_id) REFERENCES izl_t_installment (id),
  CONSTRAINT izl_ck_alloc_montant     CHECK (montant > 0)
);
COMMENT ON TABLE izl_t_payment_allocation IS 'Append-only. Comptabilité en double partie : SUM(allocations d une echeance) = montant_percu (trigger differe).';

CREATE TABLE izl_t_security_deposit (
  id                bigint GENERATED BY DEFAULT AS IDENTITY,
  lease_id          bigint      NOT NULL,
  montant           bigint      NOT NULL,
  date_reception    date        NOT NULL,
  mode              varchar(60) NOT NULL,             -- espèces, Wave… (remise en main propre)
  saisi_par         bigint      NOT NULL,             -- le bailleur
  statut            izl_typ_deposit_status NOT NULL DEFAULT 'DETENUE',
  montant_restitue  bigint      NOT NULL DEFAULT 0,
  montant_retenu    bigint      NOT NULL DEFAULT 0,
  motif_retenue     text,                             -- obligatoire si retenue > 0
  date_restitution  date,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_security_deposit  PRIMARY KEY (id),
  CONSTRAINT izl_uq_deposit_lease     UNIQUE (lease_id),
  CONSTRAINT izl_fk_deposit_lease     FOREIGN KEY (lease_id)  REFERENCES izl_t_lease (id),
  CONSTRAINT izl_fk_deposit_saisi_par FOREIGN KEY (saisi_par) REFERENCES izl_t_user (id),
  CONSTRAINT izl_ck_deposit_montant   CHECK (montant > 0),
  CONSTRAINT izl_ck_deposit_solde     CHECK (statut = 'DETENUE' OR montant_restitue + montant_retenu = montant),
  CONSTRAINT izl_ck_deposit_date      CHECK (statut <> 'RESTITUEE' OR date_restitution IS NOT NULL),
  CONSTRAINT izl_ck_deposit_motif     CHECK (motif_retenue IS NULL OR montant_retenu > 0)
);

CREATE TABLE izl_t_credit_refund (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY,
  lease_id           bigint      NOT NULL,
  payment_id         bigint      NOT NULL,           -- imputation FIFO, une ligne par paiement
  refund_ref         varchar(64) NOT NULL,           -- regroupe les lignes d'une même déclaration
  montant            bigint      NOT NULL,
  date_remboursement date        NOT NULL,
  mode               varchar(60) NOT NULL,
  declare_par        bigint      NOT NULL,           -- bailleur uniquement
  created_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_credit_refund       PRIMARY KEY (id),
  CONSTRAINT izl_fk_refund_lease        FOREIGN KEY (lease_id)     REFERENCES izl_t_lease (id),
  CONSTRAINT izl_fk_refund_payment      FOREIGN KEY (payment_id)   REFERENCES izl_t_payment (id),
  CONSTRAINT izl_fk_refund_declare_par  FOREIGN KEY (declare_par)  REFERENCES izl_t_user (id),
  CONSTRAINT izl_ck_refund_montant      CHECK (montant > 0)
);
CREATE INDEX izl_ix_refund_ref     ON izl_t_credit_refund (refund_ref);
CREATE INDEX izl_ix_refund_payment ON izl_t_credit_refund (payment_id);

CREATE TABLE izl_t_receipt (
  id                bigint GENERATED BY DEFAULT AS IDENTITY,
  lease_id          bigint      NOT NULL,
  installment_id    bigint,                         -- ACOMPTE/SOLDE uniquement
  allocation_id     bigint,                         -- ACOMPTE/SOLDE uniquement (idempotence niveau 4)
  payment_id        bigint,                         -- AVANCE uniquement
  deposit_id        bigint,                         -- CAUTION uniquement
  numero_sequence   integer,                        -- attribué par trigger si NULL
  type              izl_typ_receipt_type NOT NULL,
  statut_generation izl_typ_receipt_status NOT NULL DEFAULT 'A_GENERER',
  url_pdf           text,
  date_generation   timestamptz,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_receipt             PRIMARY KEY (id),
  CONSTRAINT izl_uq_receipt_allocation  UNIQUE (allocation_id),             -- ⚠️ 1 quittance par allocation
  CONSTRAINT izl_uq_receipt_lease_seq   UNIQUE (lease_id, numero_sequence), -- ⚠️ numérotation par bail
  CONSTRAINT izl_fk_receipt_lease       FOREIGN KEY (lease_id)       REFERENCES izl_t_lease (id),
  CONSTRAINT izl_fk_receipt_installment FOREIGN KEY (installment_id) REFERENCES izl_t_installment (id),
  CONSTRAINT izl_fk_receipt_allocation  FOREIGN KEY (allocation_id)  REFERENCES izl_t_payment_allocation (id),
  CONSTRAINT izl_fk_receipt_payment     FOREIGN KEY (payment_id)     REFERENCES izl_t_payment (id),
  CONSTRAINT izl_fk_receipt_deposit     FOREIGN KEY (deposit_id)     REFERENCES izl_t_security_deposit (id),
  CONSTRAINT izl_ck_receipt_liens CHECK (
       (type IN ('ACOMPTE','SOLDE') AND allocation_id IS NOT NULL AND payment_id IS NULL AND deposit_id IS NULL)
    OR (type = 'AVANCE'  AND allocation_id IS NULL AND payment_id IS NOT NULL AND deposit_id IS NULL)
    OR (type = 'CAUTION' AND allocation_id IS NULL AND payment_id IS NULL AND deposit_id IS NOT NULL)
  )
);
-- ⚠️ Une seule quittance d'avance par paiement ; un seul reçu de caution par dépôt
CREATE UNIQUE INDEX izl_ix_receipt_avance_payment  ON izl_t_receipt (payment_id) WHERE type = 'AVANCE';
CREATE UNIQUE INDEX izl_ix_receipt_caution_deposit ON izl_t_receipt (deposit_id) WHERE type = 'CAUTION';
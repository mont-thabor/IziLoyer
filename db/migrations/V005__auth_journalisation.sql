CREATE TABLE izl_t_otp_code (
  id         bigint GENERATED BY DEFAULT AS IDENTITY,
  telephone  varchar(16)  NOT NULL,
  code_hash  varchar(120) NOT NULL,                  -- hashé, jamais en clair
  expires_at timestamptz  NOT NULL,                  -- 5 minutes
  tentatives smallint     NOT NULL DEFAULT 0,       -- 3 max
  consomme   boolean      NOT NULL DEFAULT false,   -- usage unique
  created_at timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_otp_code   PRIMARY KEY (id),
  CONSTRAINT izl_ck_otp_tel    CHECK (telephone ~ '^\+[0-9]{8,15}$')
);
CREATE INDEX izl_ix_otp_telephone ON izl_t_otp_code (telephone, created_at DESC);
CREATE INDEX izl_ix_otp_expires   ON izl_t_otp_code (expires_at);

CREATE TABLE izl_t_refresh_token (
  id         bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id    bigint      NOT NULL,
  jti        uuid        NOT NULL DEFAULT gen_random_uuid(),
  expires_at timestamptz NOT NULL,                    -- 30 jours, rotation
  revoque    boolean     NOT NULL DEFAULT false,      -- révocation serveur par jti
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_refresh_token PRIMARY KEY (id),
  CONSTRAINT izl_uq_rt_jti        UNIQUE (jti),
  CONSTRAINT izl_fk_rt_user       FOREIGN KEY (user_id) REFERENCES izl_t_user (id)
);
CREATE INDEX izl_ix_rt_user_actifs ON izl_t_refresh_token (user_id) WHERE revoque = false;

CREATE TABLE izl_t_sms_log (
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  destinataire    varchar(16)  NOT NULL,
  type            varchar(40)  NOT NULL,   -- INVITATION_BAIL, RAPPEL_J3, CONFIRMATION_PAIEMENT,
  cle_idempotence varchar(100) NOT NULL,   -- AVOIR, ECHEC_PAIEMENT, REJET_VOIE_B…
  statut          izl_typ_sms_status NOT NULL DEFAULT 'A_ENVOYER',
  contenu         varchar(320),
  date_envoi      timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT izl_pk_sms_log   PRIMARY KEY (id),
  CONSTRAINT izl_uq_sms_cle   UNIQUE (cle_idempotence)  -- ⚠️ aucun SMS en double, même en rejeu
);
CREATE INDEX izl_ix_sms_destinataire ON izl_t_sms_log (destinataire, created_at DESC);

CREATE TABLE izl_t_audit_log (
  id         bigint GENERATED BY DEFAULT AS IDENTITY,
  survenu_at timestamptz NOT NULL DEFAULT now(),
  acteur_id  bigint,
  lease_id   bigint,                     -- sans FK : le log survit à tout
  evenement  varchar(60) NOT NULL,       -- WEBHOOK_REJETE, CLOTURE_BAIL, RELANCE_MANUELLE,
  details    jsonb       NOT NULL DEFAULT '{}'::jsonb,  -- MODIF_CREANCE, REMBOURSEMENT_CREDIT…
  CONSTRAINT izl_pk_audit_log   PRIMARY KEY (id),
  CONSTRAINT izl_fk_audit_acteur FOREIGN KEY (acteur_id) REFERENCES izl_t_user (id)
);
CREATE INDEX izl_ix_audit_evenement ON izl_t_audit_log (evenement, survenu_at DESC);
CREATE INDEX izl_ix_audit_bail      ON izl_t_audit_log (lease_id) WHERE lease_id IS NOT NULL;